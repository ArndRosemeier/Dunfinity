import { chromium } from 'playwright';
import { preview } from 'vite';
const server = await preview({ preview: { port: 5195 }, logLevel: 'silent' });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--use-angle=swiftshader', '--use-gl=angle', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 960, height: 600 } });
const t0 = Date.now();
await page.goto(server.resolvedUrls.local[0] + '?lab&seed=1&gl');
await page.waitForFunction(() => window.__ready === true, null, { timeout: 280000 });
console.log('ready', Date.now() - t0);
await browser.close(); await server.close();
