// Builds the Blender props listed in models.json with AssetGenerator (`ag.py pack`) and writes the
// pack as src/gen/models.pack.bin (fetched once by the page and each worker, read from disk by tests)
// and its model names as src/gen/models.pack.ts.
//
//   npm run props                      (needs Blender: BLENDER_BIN, or BLENDER_PYTHON with pip's bpy)
//   npm run props -- --from x.fmpk     (only rewrite the module from an existing pack)
//   AG_DIR=../assetgenerator npm run props   (an AssetGenerator checkout other than the submodule)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const { specs } = JSON.parse(readFileSync(join(root, 'tools/props/models.json'), 'utf8'));
const from = process.argv.indexOf('--from');
let pack;
if (from > 0) pack = resolve(process.argv[from + 1]);
else {
  const ag = resolve(process.env.AG_DIR ?? join(root, 'vendor/assetgenerator'));
  pack = join(mkdtempSync(join(tmpdir(), 'props-')), 'props.fmpk');
  execFileSync('python3', [join(ag, 'tools/ag.py'), 'pack', ...specs, '--out', pack], { stdio: 'inherit' });
}
const bytes = readFileSync(pack);
const names = [];
for (let at = 12, m = bytes.readUInt32LE(8); m > 0; m--) {
  const len = bytes.readUInt16LE(at);
  names.push(bytes.subarray(at + 2, at + 2 + len).toString('utf8'));
  at = (at + 2 + len + 3) & ~3;
  const n = bytes.readUInt32LE(at + 28), ni = bytes.readUInt32LE(at + 32);
  at += 36;
  at = (at + 6 * n + 3) & ~3;
  at = (at + 6 * n + 3) & ~3;
  at = (at + ni * (n > 65535 ? 4 : 2) + 3) & ~3;
}
const out = `// Generated by tools/props/pack.mjs from tools/props/models.json: do not edit. The pack itself is models.pack.bin (${bytes.length} bytes).
export type ModelName = ${names.map((n) => `'${n}'`).join(' | ')};
`;
writeFileSync(join(root, 'src/gen/models.pack.bin'), bytes);
writeFileSync(join(root, 'src/gen/models.pack.ts'), out);
console.log(`src/gen/models.pack.bin: ${names.join(', ')} (${(bytes.length / 1024).toFixed(0)} KB)`);
